local ink, glint = 0x25313d, 0xffedcf

local function layer(image, x, y, width, height, colour)
    return {image, x, y, width, height, colour >> 16, (colour >> 8) & 255, colour & 255}
end

local function dot(x, y, width, height, colour)
    return layer(ellipse, x, y, width, height, colour)
end

local function block(x, y, width, height, colour)
    return layer(rectangle, x, y, width, height, colour)
end

local function eye(x, y)
    return dot(x, y, 5, 6, ink)
end

local function light(x, y)
    return dot(x, y, 2, 2, glint)
